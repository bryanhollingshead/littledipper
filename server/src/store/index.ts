/**
 * Thin repository layer. Every record is a plain JSON document with a string _id,
 * so the backing store is swappable: SQLite by default (one file on the node's disk),
 * MongoDB when MONGODB_URI is set, and the older local JSON file for nodes created
 * before SQLite.
 */
import { existsSync, mkdirSync, readFileSync, renameSync, statSync, unlinkSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import Database from 'better-sqlite3';
import { MongoClient, type Db } from 'mongodb';

export const COLLECTIONS = [
  'nodes', 'owners', 'fields', 'contacts', 'nodeLinks', 'grants',
  'connectionRequests', 'invites', 'apiKeys', 'publicProfile', 'audit', 'challenges', 'backups',
  'records', 'domainDefs', 'messages', 'files', 'documents', 'shares', 'copies',
] as const;
export type Collection = (typeof COLLECTIONS)[number];

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export type Doc = { _id: string; [k: string]: any };
export type Filter = Record<string, unknown>;
export type FindOpts = { sort?: Record<string, 1 | -1>; limit?: number };

export interface Store {
  readonly kind: 'sqlite' | 'mongo' | 'file';
  find<T extends Doc = Doc>(coll: Collection, filter?: Filter, opts?: FindOpts): Promise<T[]>;
  findOne<T extends Doc = Doc>(coll: Collection, filter: Filter): Promise<T | null>;
  get<T extends Doc = Doc>(coll: Collection, id: string): Promise<T | null>;
  insert<T extends Doc>(coll: Collection, doc: T): Promise<T>;
  /** Shallow $set of the given keys; keys whose value is undefined are removed. */
  update(coll: Collection, id: string, patch: Record<string, unknown>): Promise<void>;
  remove(coll: Collection, id: string): Promise<void>;
  removeMany(coll: Collection, filter: Filter): Promise<number>;
  count(coll: Collection, filter?: Filter): Promise<number>;
  dump(): Promise<Record<string, Doc[]>>;
  restore(data: Record<string, Doc[]>): Promise<void>;
  /**
   * File contents (receipt photos, PDFs), kept apart from documents so the JSON store and
   * backups stay small. Callers encrypt before putting. Not part of dump() or restore().
   */
  putBlob(id: string, data: Buffer): Promise<void>;
  getBlob(id: string): Promise<Buffer | null>;
  deleteBlob(id: string): Promise<void>;
  close(): Promise<void>;
}

// ── filter matching for the file store (equality, $in, $ne, $exists) ──

function matches(doc: Doc, filter: Filter = {}): boolean {
  return Object.entries(filter).every(([k, cond]) => {
    const v = doc[k];
    if (cond && typeof cond === 'object' && !Array.isArray(cond)) {
      const c = cond as Record<string, unknown>;
      if ('$in' in c) return (c.$in as unknown[]).includes(v);
      if ('$ne' in c) return v !== c.$ne;
      if ('$exists' in c) return (v !== undefined) === c.$exists;
    }
    return v === cond;
  });
}

function sortDocs(docs: Doc[], sort?: Record<string, 1 | -1>) {
  if (!sort) return docs;
  const [[k, dir]] = Object.entries(sort);
  return docs.sort((a, b) => (a[k] < b[k] ? -dir : a[k] > b[k] ? dir : 0));
}

const clone = <T>(v: T): T => (v === undefined ? v : JSON.parse(JSON.stringify(v)));

/** File contents on the node's disk, one file per blob in <dataDir>/blobs. Shared by the file and SQLite stores. */
class DiskBlobs {
  constructor(private dir: string) {}
  // Ids are generated by us, never user input.
  private file(id: string) {
    if (!/^[a-z]+_[a-z0-9]+$/.test(id)) throw new Error('bad blob id');
    return path.join(this.dir, id);
  }
  put(id: string, data: Buffer) {
    mkdirSync(this.dir, { recursive: true });
    writeFileSync(this.file(id), data, { mode: 0o600 });
  }
  get(id: string) {
    const f = this.file(id);
    return existsSync(f) ? readFileSync(f) : null;
  }
  delete(id: string) {
    const f = this.file(id);
    if (existsSync(f)) unlinkSync(f);
  }
}

class FileStore implements Store {
  readonly kind = 'file' as const;
  private data: Record<string, Record<string, Doc>> = {};
  private mtime = 0;
  private blobs: DiskBlobs;
  constructor(private file: string) {
    mkdirSync(path.dirname(file), { recursive: true });
    this.blobs = new DiskBlobs(path.join(path.dirname(file), 'blobs'));
    this.load();
  }
  private load() {
    if (existsSync(this.file)) {
      this.data = JSON.parse(readFileSync(this.file, 'utf8'));
      this.mtime = statSync(this.file).mtimeMs;
    }
    for (const c of COLLECTIONS) this.data[c] ??= {};
  }
  /** Pick up writes made by the CLI while the server is running. */
  private fresh() {
    if (existsSync(this.file) && statSync(this.file).mtimeMs > this.mtime) this.load();
  }
  private save() {
    const tmp = this.file + '.tmp';
    writeFileSync(tmp, JSON.stringify(this.data), { mode: 0o600 });
    renameSync(tmp, this.file);
    this.mtime = statSync(this.file).mtimeMs;
  }
  async find<T extends Doc>(coll: Collection, filter?: Filter, opts: FindOpts = {}) {
    this.fresh();
    let docs = sortDocs(Object.values(this.data[coll]).filter((d) => matches(d, filter)), opts.sort);
    if (opts.limit) docs = docs.slice(0, opts.limit);
    return clone(docs) as T[];
  }
  async findOne<T extends Doc>(coll: Collection, filter: Filter) {
    return ((await this.find<T>(coll, filter, { limit: 1 }))[0] ?? null) as T | null;
  }
  async get<T extends Doc>(coll: Collection, id: string) {
    this.fresh();
    return clone(this.data[coll][id] ?? null) as T | null;
  }
  async insert<T extends Doc>(coll: Collection, doc: T) {
    this.fresh();
    if (this.data[coll][doc._id]) throw new Error(`duplicate _id ${doc._id} in ${coll}`);
    this.data[coll][doc._id] = clone(doc);
    this.save();
    return doc;
  }
  async update(coll: Collection, id: string, patch: Record<string, unknown>) {
    this.fresh();
    const d = this.data[coll][id];
    if (!d) return;
    for (const [k, v] of Object.entries(patch)) {
      if (v === undefined) delete d[k];
      else d[k] = clone(v);
    }
    this.save();
  }
  async remove(coll: Collection, id: string) {
    this.fresh();
    delete this.data[coll][id];
    this.save();
  }
  async removeMany(coll: Collection, filter: Filter) {
    this.fresh();
    const ids = Object.values(this.data[coll]).filter((d) => matches(d, filter)).map((d) => d._id);
    ids.forEach((id) => delete this.data[coll][id]);
    if (ids.length) this.save();
    return ids.length;
  }
  async count(coll: Collection, filter?: Filter) {
    return (await this.find(coll, filter)).length;
  }
  async dump() {
    this.fresh();
    return Object.fromEntries(COLLECTIONS.map((c) => [c, clone(Object.values(this.data[c]))]));
  }
  async restore(data: Record<string, Doc[]>) {
    for (const c of COLLECTIONS) this.data[c] = Object.fromEntries((data[c] || []).map((d) => [d._id, d]));
    this.save();
  }
  async putBlob(id: string, data: Buffer) { this.blobs.put(id, data); }
  async getBlob(id: string) { return this.blobs.get(id); }
  async deleteBlob(id: string) { this.blobs.delete(id); }
  async close() {}
}

// ── SQLite: one table per collection, each row an _id plus the JSON document ──

/**
 * A top-level key as an SQL expression. Filter and sort keys come from our code, never
 * user input; the literal path (not a bound parameter) is what lets the indexes below match.
 */
function field(k: string) {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(k)) throw new Error(`bad field ${k}`);
  return { value: `json_extract(doc, '$.${k}')`, type: `json_type(doc, '$.${k}')` };
}

/** v === cond, as the file store compares: types must match, and undefined means the key is missing. */
function sqlEquals(k: string, cond: unknown, params: unknown[]): string {
  const f = field(k);
  if (cond === undefined) return `${f.type} IS NULL`;
  if (cond === null) return `${f.type} = 'null'`;
  if (typeof cond === 'boolean') return `${f.type} = '${cond}'`;
  if (typeof cond === 'number') { params.push(cond); return `(${f.type} IN ('integer', 'real') AND ${f.value} = ?)`; }
  if (typeof cond === 'string') { params.push(cond); return `(${f.type} = 'text' AND ${f.value} = ?)`; }
  return '0'; // objects and arrays never compare equal
}

function sqlWhere(filter: Filter = {}, params: unknown[]): string {
  const parts = Object.entries(filter).map(([k, cond]) => {
    if (cond && typeof cond === 'object' && !Array.isArray(cond)) {
      const c = cond as Record<string, unknown>;
      if ('$in' in c) {
        const ors = (c.$in as unknown[]).map((v) => sqlEquals(k, v, params));
        return ors.length ? `(${ors.join(' OR ')})` : '0';
      }
      if ('$ne' in c) return `NOT COALESCE(${sqlEquals(k, c.$ne, params)}, 0)`;
      if ('$exists' in c) return `${field(k).type} IS ${c.$exists ? 'NOT ' : ''}NULL`;
    }
    return sqlEquals(k, cond, params);
  });
  return parts.length ? `WHERE ${parts.join(' AND ')}` : '';
}

/** The fields each collection is looked up by, as in the Mongo indexes. */
const SQLITE_INDEXES: [Collection, string[]][] = [
  ['audit', ['at']],
  ['fields', ['key']],
  ['apiKeys', ['hash']],
  ['records', ['domain', 'validFrom']],
  ['messages', ['contactId', 'createdAt']],
  ['messages', ['status']],
  ['files', ['documentId']],
  ['shares', ['tokenHash']],
  ['copies', ['contactId']],
];

class SqliteStore implements Store {
  readonly kind = 'sqlite' as const;
  private db: Database.Database;
  private blobs: DiskBlobs;
  constructor(file: string) {
    mkdirSync(path.dirname(file), { recursive: true });
    // An empty file is a valid empty database; creating it first keeps it owner-only.
    if (!existsSync(file)) writeFileSync(file, '', { mode: 0o600 });
    this.db = new Database(file);
    this.db.pragma('journal_mode = WAL');
    this.db.pragma('synchronous = FULL'); // a life record: every commit reaches the disk
    this.db.pragma('busy_timeout = 5000'); // the CLI may write while the server runs
    for (const c of COLLECTIONS) this.db.exec(`CREATE TABLE IF NOT EXISTS "${c}" (_id TEXT PRIMARY KEY, doc TEXT NOT NULL)`);
    for (const [c, keys] of SQLITE_INDEXES) {
      this.db.exec(`CREATE INDEX IF NOT EXISTS "${c}_${keys.join('_')}" ON "${c}" (${keys.map((k) => field(k).value).join(', ')})`);
    }
    this.blobs = new DiskBlobs(path.join(path.dirname(file), 'blobs'));
  }
  private getSync(coll: Collection, id: string): Doc | null {
    const row = this.db.prepare(`SELECT doc FROM "${coll}" WHERE _id = ?`).get(id) as { doc: string } | undefined;
    return row ? JSON.parse(row.doc) : null;
  }
  async find<T extends Doc>(coll: Collection, filter?: Filter, opts: FindOpts = {}) {
    const params: unknown[] = [];
    let sql = `SELECT doc FROM "${coll}" ${sqlWhere(filter, params)}`;
    // rowid keeps insertion order, as the file store does, for ties and unsorted reads.
    const sort = opts.sort && Object.entries(opts.sort)[0];
    sql += sort ? ` ORDER BY ${field(sort[0]).value} ${sort[1] === -1 ? 'DESC' : 'ASC'}, rowid` : ' ORDER BY rowid';
    if (opts.limit) { sql += ' LIMIT ?'; params.push(opts.limit); }
    const rows = this.db.prepare(sql).all(...params) as { doc: string }[];
    return rows.map((r) => JSON.parse(r.doc)) as T[];
  }
  async findOne<T extends Doc>(coll: Collection, filter: Filter) {
    return ((await this.find<T>(coll, filter, { limit: 1 }))[0] ?? null) as T | null;
  }
  async get<T extends Doc>(coll: Collection, id: string) {
    return this.getSync(coll, id) as T | null;
  }
  async insert<T extends Doc>(coll: Collection, doc: T) {
    try {
      this.db.prepare(`INSERT INTO "${coll}" (_id, doc) VALUES (?, ?)`).run(doc._id, JSON.stringify(doc));
    } catch (e) {
      if ((e as { code?: string }).code === 'SQLITE_CONSTRAINT_PRIMARYKEY') throw new Error(`duplicate _id ${doc._id} in ${coll}`);
      throw e;
    }
    return doc;
  }
  async update(coll: Collection, id: string, patch: Record<string, unknown>) {
    this.db.transaction(() => {
      const d = this.getSync(coll, id);
      if (!d) return;
      for (const [k, v] of Object.entries(patch)) {
        if (v === undefined) delete d[k];
        else d[k] = v;
      }
      this.db.prepare(`UPDATE "${coll}" SET doc = ? WHERE _id = ?`).run(JSON.stringify(d), id);
    })();
  }
  async remove(coll: Collection, id: string) {
    this.db.prepare(`DELETE FROM "${coll}" WHERE _id = ?`).run(id);
  }
  async removeMany(coll: Collection, filter: Filter) {
    const params: unknown[] = [];
    return this.db.prepare(`DELETE FROM "${coll}" ${sqlWhere(filter, params)}`).run(...params).changes;
  }
  async count(coll: Collection, filter?: Filter) {
    const params: unknown[] = [];
    return (this.db.prepare(`SELECT COUNT(*) AS n FROM "${coll}" ${sqlWhere(filter, params)}`).get(...params) as { n: number }).n;
  }
  async dump() {
    return Object.fromEntries(COLLECTIONS.map((c) => [
      c, (this.db.prepare(`SELECT doc FROM "${c}" ORDER BY rowid`).all() as { doc: string }[]).map((r) => JSON.parse(r.doc)),
    ]));
  }
  async restore(data: Record<string, Doc[]>) {
    this.db.transaction(() => {
      for (const c of COLLECTIONS) {
        this.db.prepare(`DELETE FROM "${c}"`).run();
        const ins = this.db.prepare(`INSERT INTO "${c}" (_id, doc) VALUES (?, ?)`);
        for (const d of data[c] || []) ins.run(d._id, JSON.stringify(d));
      }
    })();
  }
  async putBlob(id: string, data: Buffer) { this.blobs.put(id, data); }
  async getBlob(id: string) { return this.blobs.get(id); }
  async deleteBlob(id: string) { this.blobs.delete(id); }
  async close() {
    this.db.close();
  }
}

class MongoStore implements Store {
  readonly kind = 'mongo' as const;
  private constructor(private client: MongoClient, private db: Db) {}
  static async connect(uri: string, dbName: string) {
    const client = new MongoClient(uri);
    await client.connect();
    const db = client.db(dbName);
    await db.collection('audit').createIndex({ at: -1 });
    await db.collection('fields').createIndex({ key: 1 }, { unique: true });
    await db.collection('apiKeys').createIndex({ hash: 1 });
    await db.collection('records').createIndex({ domain: 1, validFrom: -1 });
    await db.collection('messages').createIndex({ contactId: 1, createdAt: -1 });
    await db.collection('messages').createIndex({ status: 1 });
    await db.collection('files').createIndex({ documentId: 1 });
    await db.collection('shares').createIndex({ tokenHash: 1 });
    await db.collection('copies').createIndex({ contactId: 1 });
    return new MongoStore(client, db);
  }
  // The driver's types assume ObjectId _ids; ours are strings, so loosen them here.
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  private c(coll: Collection) { return this.db.collection<any>(coll); }
  async find<T extends Doc>(coll: Collection, filter: Filter = {}, opts: FindOpts = {}) {
    let cur = this.c(coll).find(filter);
    if (opts.sort) cur = cur.sort(opts.sort);
    if (opts.limit) cur = cur.limit(opts.limit);
    return (await cur.toArray()) as T[];
  }
  async findOne<T extends Doc>(coll: Collection, filter: Filter) {
    return (await this.c(coll).findOne(filter)) as T | null;
  }
  async get<T extends Doc>(coll: Collection, id: string) {
    return (await this.c(coll).findOne({ _id: id })) as T | null;
  }
  async insert<T extends Doc>(coll: Collection, doc: T) {
    await this.c(coll).insertOne(doc);
    return doc;
  }
  async update(coll: Collection, id: string, patch: Record<string, unknown>) {
    const $set: Record<string, unknown> = {}, $unset: Record<string, ''> = {};
    for (const [k, v] of Object.entries(patch)) (v === undefined ? ($unset[k] = '') : ($set[k] = v));
    const upd: Record<string, unknown> = {};
    if (Object.keys($set).length) upd.$set = $set;
    if (Object.keys($unset).length) upd.$unset = $unset;
    if (Object.keys(upd).length) await this.c(coll).updateOne({ _id: id }, upd);
  }
  async remove(coll: Collection, id: string) {
    await this.c(coll).deleteOne({ _id: id });
  }
  async removeMany(coll: Collection, filter: Filter) {
    return (await this.c(coll).deleteMany(filter)).deletedCount;
  }
  async count(coll: Collection, filter: Filter = {}) {
    return this.c(coll).countDocuments(filter);
  }
  async dump() {
    const out: Record<string, Doc[]> = {};
    for (const c of COLLECTIONS) out[c] = (await this.c(c).find({}).toArray()) as Doc[];
    return out;
  }
  async restore(data: Record<string, Doc[]>) {
    for (const c of COLLECTIONS) {
      await this.c(c).deleteMany({});
      if (data[c]?.length) await this.c(c).insertMany(data[c]);
    }
  }
  // A separate collection outside COLLECTIONS, so dump() and backups skip it. Files are capped well under 16 MB.
  async putBlob(id: string, data: Buffer) {
    await this.db.collection<{ _id: string; data: Buffer }>('blobs').replaceOne({ _id: id }, { data }, { upsert: true });
  }
  async getBlob(id: string) {
    const d = await this.db.collection<{ _id: string; data: { buffer: Uint8Array } }>('blobs').findOne({ _id: id });
    return d ? Buffer.from(d.data.buffer) : null;
  }
  async deleteBlob(id: string) {
    await this.db.collection<{ _id: string }>('blobs').deleteOne({ _id: id });
  }
  async close() {
    await this.client.close();
  }
}

export const SQLITE_FILE = 'little-dipper.db';

export async function openStore(opts: { mongoUri: string; mongoDb: string; dataDir: string }): Promise<Store> {
  if (opts.mongoUri) return MongoStore.connect(opts.mongoUri, opts.mongoDb);
  const db = path.join(opts.dataDir, SQLITE_FILE), legacy = path.join(opts.dataDir, 'store.json');
  // A node created before SQLite keeps its JSON file until that's migrated, so it never starts up empty.
  if (existsSync(legacy) && !existsSync(db)) return new FileStore(legacy);
  return new SqliteStore(db);
}
